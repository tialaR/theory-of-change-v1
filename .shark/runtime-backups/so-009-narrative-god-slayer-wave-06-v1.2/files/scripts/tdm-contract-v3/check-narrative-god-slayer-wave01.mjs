import fs from 'node:fs';
const root='src/features/theory-of-change/components/result-view/result-theory-narrative';
const mapper=`${root}/theory-narrative.mapper.ts`;
const primitives=`${root}/narrative-mapping/theory-document-builders.ts`;
const figures=`${root}/narrative-mapping/theory-figure-builders.ts`;
const pages=`${root}/narrative-mapping/theory-page-builders.ts`;
const fail=(m)=>{console.error(`FAIL ${m}`);process.exit(1)};
for(const file of [mapper,primitives,figures,pages]) if(!fs.existsSync(file)) fail(`missing ${file}`);
const source=fs.readFileSync(mapper,'utf8');
const lines=source.split(/\r?\n/).length;
if(lines>960) fail(`narrative mapper budget exceeded: ${lines} > 960`);
for(const token of ['function nextId(','function nodeRefs(','function paragraph(','function pushParagraph(','function buildOverviewFigure(','function buildResourcesFigure(','function buildConvergenceFigure(']) if(source.includes(token)) fail(`mapping ownership leaked back into mapper: ${token}`);
if(!source.includes("./narrative-mapping/theory-document-builders")) fail('mapper must consume document builder owner');
const pageSource=fs.readFileSync(pages,'utf8');
if(!source.includes("./narrative-mapping/theory-figure-builders") && !pageSource.includes("./theory-figure-builders")) fail('narrative assembly must consume figure builder owner directly or through page assembly');
const ps=fs.readFileSync(primitives,'utf8');
for(const token of ['nextId','nodeRefs','pushParagraph','numberSections']) if(!ps.includes(token)) fail(`document builder lost ownership: ${token}`);
const fsr=fs.readFileSync(figures,'utf8');
for(const token of ['buildOverviewFigure','buildResourcesFigure','buildConvergenceFigure','titlesByStage']) if(!fsr.includes(token)) fail(`figure builder lost ownership: ${token}`);
if([...fs.readdirSync(root,{recursive:true})].some(p=>String(p).endsWith('.scss'))) fail('.scss is forbidden in narrative feature');
console.log('PASS SO-009 Narrative God Slayer Wave 01: document primitives and figure mapping ownership are split and armored.');
